import type * as ts from 'typescript';
import type { ConfigInfo } from './config-discovery';
import { collectClassFacts } from './cohesion';
import { runCorrectness } from './correctness';
import { modulePathFor } from './context-selection';
import type { AnalysisEnv } from './env';
import { collectMethodFacts } from './method-facts';
import { ordinal } from './paths';
import { createContextProgram } from './program-factory';
import {
  compareReasons,
  reason,
  ReasonCodes,
  type ClassFact,
  type ContextFacts,
  type CorrectnessRuleRequest,
  type FileFact,
  type Reason,
} from './protocol';
import type { SourceBundle } from './source-bundle';
import { collectTypeFacts } from './type-facts';

export interface ContextRequest {
  env: AnalysisEnv;
  config: ConfigInfo;
  focus: ReadonlySet<string>;
  rules: CorrectnessRuleRequest[];
}

const GENERATED_NAME = /\.(generated|g)\.(ts|tsx|mts|cts)$/i;
const GENERATED_MARKER = /@generated|<auto-generated>/i;

function isGenerated(bundle: SourceBundle): boolean {
  const header = bundle.sourceFile.text.split(/\r?\n/, 10).join('\n');
  return GENERATED_NAME.test(bundle.file) || GENERATED_MARKER.test(header);
}

function buildFileFact(bundle: SourceBundle): FileFact {
  return {
    path: bundle.file,
    codeLines: bundle.tokens.countLines(0, Number.MAX_SAFE_INTEGER),
    generated: isGenerated(bundle),
    methods: collectMethodFacts(bundle.namer, bundle.tokens),
  };
}

function focusBundles(request: ContextRequest, bundles: Map<string, SourceBundle>): SourceBundle[] {
  return request.config.ownedFiles
    .filter((file) => request.focus.has(file))
    .map((file) => bundles.get(file))
    .filter((bundle): bundle is SourceBundle => bundle !== undefined);
}

function classFacts(checker: ts.TypeChecker, bundles: SourceBundle[]): ClassFact[] {
  return bundles.flatMap((bundle) => collectClassFacts(bundle.namer, checker));
}

function ownershipFailures(request: ContextRequest, modulePath: string | undefined, missing: string[]): Reason[] {
  const contextId = request.config.path;
  const failures = request.config.errors.map((message) =>
    reason(ReasonCodes.ProjectLoadFailed, `Cannot load ${contextId}: ${message}`, null, contextId),
  );
  if (modulePath === undefined) {
    failures.push(reason(ReasonCodes.UnresolvedOwnership, `No package.json owns ${contextId}.`, null, contextId));
  }
  for (const file of missing) {
    failures.push(reason(ReasonCodes.UnreadableSource, `Cannot read ${file}.`, null, contextId));
  }
  return failures;
}

/** Facts for one standalone tsconfig: metrics for focus files, types for all owned files, ESLint diagnostics. */
export async function analyzeContext(request: ContextRequest): Promise<ContextFacts> {
  const { env, config } = request;
  const modulePath = modulePathFor(config, env);
  const { program, bundles, missing } = createContextProgram(env, config);
  const focused = focusBundles(request, bundles);
  const loaded = config.errors.length === 0;
  const correctness = loaded
    ? await runCorrectness({ env, contextId: config.path, tsconfigPath: env.paths.toAbs(config.path), program, bundles, rules: request.rules })
    : { diagnostics: [], failures: [] };
  return {
    contextId: config.path,
    language: 'typescript',
    configPath: config.path,
    framework: null,
    modulePath,
    ownedFiles: config.ownedFiles,
    files: focused.map(buildFileFact).sort((a, b) => ordinal(a.path, b.path)),
    classes: loaded ? classFacts(program.getTypeChecker(), focused) : [],
    types: [...bundles.values()].flatMap((bundle) => collectTypeFacts(bundle.namer)),
    diagnostics: correctness.diagnostics,
    failures: [...ownershipFailures(request, modulePath ?? undefined, missing), ...correctness.failures].sort(compareReasons),
  };
}
