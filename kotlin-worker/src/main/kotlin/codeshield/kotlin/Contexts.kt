package codeshield.kotlin

/** One analysis context: the main or the test sources of one Gradle project. */
internal class ContextPlan(val project: GradleProject, val test: Boolean, val ownedFiles: List<String>) {
    val contextId: String get() = "${project.contextPrefix}|${if (test) TEST else MAIN}"

    /** Main sources are the module the main-sequence rule measures; test sources are not a module of their own. */
    val modulePath: String? get() = if (test) null else project.script

    /** A context is analyzed when it owns a changed source or when a script that configures it changed. */
    fun selected(focus: Set<String>, changed: Set<String>): Boolean =
        ownedFiles.any { it in focus } || project.chain.any { it in changed }

    companion object {
        const val MAIN = "main"
        const val TEST = "test"

        /**
         * The contexts of every project, sorted by ID. The main context of a project with a build script always exists, so
         * a changed script is assessed even before the project has sources; other contexts exist only when they own files.
         */
        fun all(model: GradleModel): List<ContextPlan> {
            val owned = HashMap<Pair<GradleProject, Boolean>, MutableList<String>>()
            model.owners.forEach { (file, owner) -> owned.getOrPut(owner.project to owner.test) { ArrayList() }.add(file) }
            return model.projects.flatMap { project -> listOf(false, true).mapNotNull { plan(project, it, owned[project to it]) } }
                .sortedBy { it.contextId }
        }

        private fun plan(project: GradleProject, test: Boolean, files: List<String>?): ContextPlan? =
            if (files == null && (test || project.script == null)) null else ContextPlan(project, test, ordinalSorted(files.orEmpty()))
    }
}

/** A Kotlin source as loaded for analysis; [problem] explains why it is missing or only partly parsed. */
internal class LoadedSource(val path: String, val unit: SourceUnit?, val problem: String?)

/** Reads and parses Kotlin sources, recording each as an analysis input. */
internal class SourceLoader(private val ledger: InputLedger, private val parser: KotlinParser) {
    fun load(path: String): LoadedSource {
        val text = ledger.readRepoText(path) ?: return LoadedSource(path, null, "Cannot read $path.")
        val unit = try {
            SourceUnit(parser.parse(path, text))
        } catch (error: Exception) {
            return LoadedSource(path, null, "Cannot parse $path: ${error.message ?: error.javaClass.simpleName}")
        } catch (error: StackOverflowError) {
            return LoadedSource(path, null, "Cannot parse $path: the file is nested too deeply.")
        }
        val syntax = unit.parsed.syntaxError ?: return LoadedSource(path, unit, null)
        return LoadedSource(path, unit, "Cannot parse $path: syntax error at $syntax.")
    }
}

/**
 * Facts for one context: metrics and cohesion for its changed (focus) files; types and detekt diagnostics for every file
 * it owns, because abstractness and baseline attribution need the whole context.
 */
internal class ContextAnalysis(
    private val loader: SourceLoader,
    private val focus: Set<String>,
    private val rules: List<CorrectnessRuleRequest>,
) {
    fun analyze(plan: ContextPlan): ContextFacts {
        val loaded = plan.ownedFiles.map(loader::load)
        val sources = loaded.mapNotNull { it.unit }
        val focused = sources.filter { it.path in focus }
        val correctness = Correctness(plan.contextId, plan.project.configPath).run(sources, rules)
        val unreadable = loaded.mapNotNull { source -> source.problem?.let { Reason(ReasonCodes.UNREADABLE_SOURCE, it, null, plan.contextId) } }
        return ContextFacts(
            contextId = plan.contextId,
            configPath = plan.project.configPath,
            modulePath = plan.modulePath,
            ownedFiles = plan.ownedFiles,
            files = focused.map(::fileFact),
            classes = focused.flatMap(Cohesion::collect),
            types = TypeFacts.collect(sources),
            diagnostics = correctness.diagnostics,
            failures = (plan.project.failures + unreadable + correctness.failures).sorted(),
        )
    }

    private fun fileFact(source: SourceUnit): FileFact =
        FileFact(source.path, source.code.total(), isGenerated(source.parsed.text), MethodMetrics.collect(source))

    companion object {
        private val GENERATED_MARKER = Regex("@generated|<auto-generated>", RegexOption.IGNORE_CASE)

        /** A generator marker in the first ten lines, as for TypeScript; [text] has `\n` line breaks only. */
        fun isGenerated(text: String): Boolean = GENERATED_MARKER.containsMatchIn(text.split('\n', limit = 11).take(10).joinToString("\n"))
    }
}
