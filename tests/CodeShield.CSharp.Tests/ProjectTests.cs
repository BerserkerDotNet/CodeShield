using CodeShield.Abstractions;

namespace CodeShield.CSharp.Tests;

public sealed class ProjectTests
{
    private const string Simple = "public class A { int a; public int X() => a; }";

    [Fact]
    public async Task Multi_targeted_project_gives_one_context_per_framework()
    {
        using var fixture = new Fixture();
        fixture.Project(xml: Fixture.ProjectXml.Replace("<TargetFramework>net10.0</TargetFramework>", "<TargetFrameworks>net10.0;net9.0</TargetFrameworks>"))
            .Write("A.cs", Simple);
        var analysis = await fixture.AnalyzeAsync(["A.cs"]);
        Assert.Equal(["App.csproj|net10.0", "App.csproj|net9.0"], analysis.Contexts.Select(c => c.ContextId).Order(StringComparer.Ordinal));
        Assert.All(analysis.Contexts, c => Assert.Equal("App.csproj", c.ModulePath));
    }

    [Fact]
    public async Task Linked_file_can_have_two_owners_and_unowned_files_are_reported()
    {
        using var fixture = new Fixture();
        const string Linked = "<Project Sdk=\"Microsoft.NET.Sdk\"><PropertyGroup><TargetFramework>net10.0</TargetFramework></PropertyGroup>" +
            "<ItemGroup><Compile Include=\"..\\Shared\\S.cs\" Link=\"S.cs\" /></ItemGroup></Project>";
        fixture.Project("a/a.csproj", Linked).Project("b/b.csproj", Linked)
            .Write("Shared/S.cs", Simple).Write("Stray/T.cs", Simple);
        // Stray/T.cs is outside any project directory glob.
        var analysis = await fixture.AnalyzeAsync(["Shared/S.cs", "Stray/T.cs"]);
        Assert.Equal(["a/a.csproj|net10.0", "b/b.csproj|net10.0"], analysis.Contexts.Select(c => c.ContextId).Order(StringComparer.Ordinal));
        Assert.All(analysis.Contexts, c => Assert.Contains("Shared/S.cs", c.OwnedFiles));
        Assert.Equal(["Stray/T.cs"], analysis.UnownedFiles);
    }

    [Fact]
    public async Task Missing_package_fails_type_aware_rules_but_keeps_method_metrics()
    {
        using var fixture = new Fixture();
        fixture.Project(xml: Fixture.ProjectXml.Replace("</Project>", "<ItemGroup><PackageReference Include=\"Not.Installed.Pkg\" Version=\"1.0.0\" /></ItemGroup></Project>"))
            .Write("A.cs", Simple);
        var context = await fixture.SingleAsync("A.cs");
        Assert.True(context.Fails("cohesion.lcom4", "MISSING_DEPENDENCY"));
        Assert.True(context.Fails("correctness.csharp.ca2000", "MISSING_DEPENDENCY"));
        Assert.False(context.Fails("complexity.cyclomatic", "MISSING_DEPENDENCY"));
        Assert.Single(context.Files.Single().Methods);
    }

    [Fact]
    public async Task Unresolvable_type_gives_missing_dependency()
    {
        using var fixture = new Fixture();
        fixture.Project().Write("A.cs", "public class A { Nope.Missing m; }");
        var context = await fixture.SingleAsync("A.cs");
        Assert.True(context.Fails("cohesion.lcom4", "MISSING_DEPENDENCY"));
    }

    [Fact]
    public async Task Generated_files_are_marked_generated_and_have_no_class_facts()
    {
        using var fixture = new Fixture();
        fixture.Project().Write("Gen.g.cs", Simple).Write("obj/Other.cs", Simple.Replace("class A", "class B"))
            .Write("Auto.cs", "// <auto-generated/>\n" + Simple.Replace("class A", "class C"));
        var context = await fixture.SingleAsync("Gen.g.cs", "Auto.cs");
        Assert.All(context.Files, file => Assert.True(file.Generated));
        Assert.Empty(context.Classes);
        Assert.Empty(context.Types);
    }

    [Fact]
    public async Task Broken_project_fails_with_project_load_failed_for_all_rules()
    {
        using var fixture = new Fixture();
        fixture.Project(xml: "<Project Sdk=\"Microsoft.NET.Sdk\"><PropertyGroup>").Write("A.cs", Simple);
        var analysis = await fixture.AnalyzeAsync(["A.cs"]);
        var context = Assert.Single(analysis.Contexts);
        var reason = Assert.Single(context.Failures);
        Assert.Equal("PROJECT_LOAD_FAILED", reason.Code);
        Assert.Null(reason.RuleId);
        Assert.Empty(analysis.UnownedFiles);
    }

    [Fact]
    public async Task Changed_project_file_selects_its_contexts_without_focus_files()
    {
        using var fixture = new Fixture();
        fixture.Project().Project("Other/o.csproj").Write("A.cs", Simple);
        var analysis = await fixture.AnalyzeAsync([], ["App.csproj"]);
        Assert.Equal("App.csproj|net10.0", Assert.Single(analysis.Contexts).ContextId);
    }

    [Fact]
    public async Task Changed_imported_props_file_selects_the_importing_project()
    {
        using var fixture = new Fixture();
        fixture.Project(xml: Fixture.ProjectXml.Replace("</Project>", "<Import Project=\"common.props\" /></Project>"))
            .Write("common.props", "<Project><PropertyGroup><DefineConstants>$(DefineConstants);X</DefineConstants></PropertyGroup></Project>")
            .Write("A.cs", Simple);
        var analysis = await fixture.AnalyzeAsync([], ["common.props"]);
        Assert.Single(analysis.Contexts);
    }

    [Fact]
    public async Task Define_constants_and_framework_symbols_apply_to_parsing()
    {
        using var fixture = new Fixture();
        fixture.Project(xml: Fixture.ProjectXml.Replace("</PropertyGroup>", "<DefineConstants>CUSTOM</DefineConstants></PropertyGroup>"))
            .Write("A.cs", "public class A { public int M() {\n#if CUSTOM && NET10_0\nreturn 1;\n#else\nif (true) { }\nreturn 2;\n#endif\n} }");
        var context = await fixture.SingleAsync("A.cs");
        Assert.Equal(1, context.Method("A.M()").Complexity);
        Assert.Equal(3, context.Method("A.M()").CodeLines);
    }

    [Fact]
    public async Task Module_graph_has_project_reference_edges_and_unresolved_references()
    {
        using var fixture = new Fixture();
        fixture.Project("app/app.csproj", Fixture.ProjectXml.Replace("</Project>",
                "<ItemGroup><ProjectReference Include=\"..\\lib\\lib.csproj\" /><ProjectReference Include=\"..\\..\\outside\\x.csproj\" /></ItemGroup></Project>"))
            .Project("lib/lib.csproj").Write("app/P.cs", "public class P { public L M() => new L(); }").Write("lib/L.cs", "public class L { }");
        var analysis = await fixture.AnalyzeAsync(["app/P.cs"]);
        Assert.Equal(["app/app.csproj", "lib/lib.csproj"], analysis.Graph.Modules);
        var edge = Assert.Single(analysis.Graph.Edges);
        Assert.Equal(new ModuleEdge("app/app.csproj", "lib/lib.csproj", false), edge);
        Assert.Contains(analysis.Graph.Unresolved, r => r.Code == "MISSING_DEPENDENCY");
        Assert.Empty(analysis.Graph.FileImports);
    }

    [Fact]
    public async Task Project_references_provide_types_to_the_compilation()
    {
        using var fixture = new Fixture();
        fixture.Project("app/app.csproj", Fixture.ProjectXml.Replace("</Project>", "<ItemGroup><ProjectReference Include=\"..\\lib\\lib.csproj\" /></ItemGroup></Project>"))
            .Project("lib/lib.csproj").Write("app/P.cs", "public class P { L l = new L(); public L M() => l; }").Write("lib/L.cs", "public class L { }");
        var analysis = await fixture.AnalyzeAsync(["app/P.cs"]);
        var context = Assert.Single(analysis.Contexts);
        Assert.Empty(context.Failures);
        Assert.Single(context.Classes);
    }

    [Fact]
    public async Task Tokenization_returns_exact_non_trivia_tokens()
    {
        using var fixture = new Fixture();
        fixture.Write("A.cs", "// hi\nclass A\n{\n  int x = 12;\n}\n");
        var result = await new CSharpLanguageAnalyzer().TokenizeAsync(new TokenizeRequest(fixture.Root, ["A.cs"]), CancellationToken.None);
        Assert.Empty(result.Failures);
        var tokens = Assert.Single(result.Files).Tokens;
        Assert.Equal(["class", "A", "{", "int", "x", "=", "12", ";", "}"], tokens.Select(t => t.Text));
        Assert.Equal("ClassKeyword", tokens[0].Kind);
        Assert.Equal("NumericLiteralToken", tokens[6].Kind);
        Assert.Equal((2, 1), (tokens[0].Line, tokens[0].Column));
        Assert.Equal((4, 11), (tokens[6].Line, tokens[6].Column));
        Assert.Equal(6, tokens[0].Offset);
    }

    [Fact]
    public async Task Tokenization_reports_unreadable_files()
    {
        using var fixture = new Fixture();
        var result = await new CSharpLanguageAnalyzer().TokenizeAsync(new TokenizeRequest(fixture.Root, ["Missing.cs"]), CancellationToken.None);
        Assert.Contains(result.Failures, r => r.Code == "UNREADABLE_SOURCE");
    }
}
